function pushContent(date, type, sequence, title, payload) {
  lines.push(`INSERT INTO japanese_jlpt_daily_contents(plan_id,study_date,content_type,sequence_no,title,payload_json)`);
  lines.push(`SELECT id,${sql(date)},${sql(type)},${sequence},${sql(title)},'${compactJson(payload)}'`);
  lines.push(`FROM japanese_jlpt_study_plans WHERE plan_code=${sql(manifest.planCode)};`);
}

for (const day of days) {
  day.vocabQuestions.forEach((q, index) => pushContent(day.date, 'vocab_question', index + 1, '文字・語彙', {
    type: q.type,
    wordKey: q.wordKey,
    prompt: q.prompt,
    options: q.options,
    answer: q.answer,
    explanation: q.explanation_ko,
    explanationKo: q.explanation_ko,
  }));
  day.grammarLessons.forEach((g, index) => pushContent(day.date, 'grammar', index + 1, g.pattern, {
    pattern: g.pattern,
    meaningKo: g.meaning_ko,
    explanation: g.explanation_ko,
    examples: g.examples,
  }));
  day.grammarQuestions.forEach((q, index) => pushContent(day.date, 'grammar_question', index + 1, '文法', {
    prompt: q.prompt,
    options: q.options,
    answer: q.answer,
    explanation: q.explanation_ko,
    explanationKo: q.explanation_ko,
  }));
  day.readingSets.forEach((r, index) => pushContent(day.date, 'reading', index + 1, r.title, {
    passage: r.passage,
    questions: r.questions.map((q) => ({
      prompt: q.prompt,
      options: q.options,
      answer: q.answer,
      explanation: q.explanation_ko,
      explanationKo: q.explanation_ko,
    })),
  }));
}

