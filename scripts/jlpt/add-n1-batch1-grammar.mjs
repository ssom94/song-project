const normalize = (value = '') => String(value).normalize('NFKC').replace(/\s+/g, ' ').trim();
function strip(sentence, pattern) {
	const literal = pattern.replace('〜', '');
	const direct = sentence.replace(literal, '（　）');
	if (direct !== sentence) return direct;
	const conjugated = new Map([
		['〜たところで', /(?:た|だ)ところで/u],
		['〜にたえる', /にも?たえる/u],
		['〜までもない', /までもな(?:い|く)/u],
		['〜を禁じ得ない', /を禁じ得な(?:い|かった)/u],
		['〜いかんだ', /いかんで/u],
		['〜ようと', /(?:であろう|だろう)と/u],
		['〜限りだ', /限り(?:だ|です)/u],
		['〜始末だ', /始末(?:だ|になった)/u],
		['〜かねる', /かね(?:ます|ている)/u],
		['〜そびれる', /そびれ(?:た|て)/u],
		['〜めく', /めい(?:て|た)/u],
		['〜といい〜といい', /といい[^、]+といい/u],
		['〜なり〜なり', /なり[^、]+なり/u],
		['〜にあたらない', /にはあたらない/u],
		['〜を余儀なくされる', /を余儀なくされた/u],
		['〜を余儀なくさせる', /を余儀なくさせた/u],
		['〜つ〜つ', /(?:持ちつ持たれつ|行きつ戻りつ)/u],
		['〜やら〜やら', /(?:手続きやら荷造りやら|驚くやらうれしいやら)/u],
		['〜ようにも〜ない', /(?:確認しようにも確認できない|知らせようにも知らせられない)/u],
		['〜たりとも〜ない', /(?:一文字たりとも外部に漏らしてはならない|一瞬たりとも警戒を緩められない)/u],
		['〜だろうが〜だろうが', /(?:賛成だろうが反対だろうが|平日だろうが休日だろうが)/u],
		['〜ては〜ては', /(?:書いては消し、書いては消し|試しては直し、試しては直し)/u],
		['〜てばかりはいられない', /(?:頼ってばかりはいられない|悔やんでばかりはいられない)/u],
		['〜に至る', /に至った/u],
		['〜にせよ〜にせよ', /(?:採用するにせよ見送るにせよ|賛成するにせよ反対するにせよ)/u],
		['〜ようが〜まいが', /(?:反対しようがしまいが|降ろうが降るまいが)/u],
	]);
	const expression = conjugated.get(pattern);
	return expression ? sentence.replace(expression, '（　）') : sentence;
}

