const doc = JSON.parse(await fs.readFile(FILE, 'utf8'));
if (doc.days.length !== 14 || sets.length !== 14) throw new Error('Expected exactly 14 days and reading sets.');
const normalize = (value = '') => String(value).normalize('NFKC').replace(/\s+/g, ' ').trim();
const signatures = new Set();
for (let dayIndex = 0; dayIndex < 14; dayIndex += 1) {
	const source = sets[dayIndex];
	const questions = source.questions.map(([prompt, options, answer, explanation_ko], index) => ({ sequence: index + 1, prompt, options, answer, explanation_ko }));
	doc.days[dayIndex].readingSets = [{ sequence: 1, title: source.title, passage: source.passage, questions }];
	for (const question of questions) {
		if (question.options.length !== 4 || new Set(question.options.map(normalize)).size !== 4) throw new Error(`${doc.days[dayIndex].date}: duplicate reading option`);
		if (question.options.filter((option) => normalize(option) === normalize(question.answer)).length !== 1) throw new Error(`${doc.days[dayIndex].date}: reading answer mismatch`);
		const signature = normalize(`${question.prompt}\n${question.options.join('\n')}`);
		if (signatures.has(signature)) throw new Error(`${doc.days[dayIndex].date}: duplicate reading MCQ`);
		signatures.add(signature);
	}
}
doc.status = 'complete_content_editorial_review_pending';
doc.checks.readingSetCount = 14;
doc.checks.readingQuestionCount = 42;
doc.checks.uniqueReadingMcqCount = signatures.size;
doc.checks.readingAnswerChecksPassed = true;
doc.checks.readingPending = false;
await fs.writeFile(FILE, `${JSON.stringify(doc, null, 2)}\n`);
