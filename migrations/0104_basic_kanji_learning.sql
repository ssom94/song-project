CREATE TABLE IF NOT EXISTS japanese_admin_basic_kanji_states (
    admin_id INTEGER NOT NULL,
    kanji TEXT NOT NULL,
    learning_state TEXT NOT NULL DEFAULT 'unlearned'
        CHECK (learning_state IN ('unlearned', 'mastered')),
